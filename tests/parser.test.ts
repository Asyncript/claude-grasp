import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { classifyUserLine } from '../parser/human';
import { approvalOf, BASH_BULK_LIMIT, SessionParser } from '../parser/session';
import { cleanPromptText, extractMentions, extractSymbols, isBareApproval, isCorrection, isQuestion } from '../parser/text';
import { SESSION_IDS } from '../fixtures/repo';

const user = (content: unknown, extra: Record<string, unknown> = {}) => ({ type: 'user', uuid: `u${Math.random()}`, timestamp: '2026-10-30T10:00:00.000Z', message: { role: 'user', content }, ...extra });
const toolUse = (id: string, name: string, input: Record<string, unknown>) => ({ type: 'assistant', timestamp: '2026-10-30T10:00:01.000Z', message: { content: [{ type: 'tool_use', id, name, input }] } });
const toolResult = (id: string, toolUseResult: unknown, extra: Record<string, unknown> = {}, block: Record<string, unknown> = {}) =>
  user([{ type: 'tool_result', tool_use_id: id, content: 'ok', ...block }], { toolUseResult, ...extra });

function parse(lines: unknown[], opts: { sidechain?: boolean } = {}) {
  const p = new SessionParser(opts);
  for (const l of lines) p.feedLine(typeof l === 'string' ? l : JSON.stringify(l));
  return { ...p.drain(), state: p.state };
}

describe('classifyUserLine', () => {
  it('recognizes typed prompts', () => {
    expect(classifyUserLine(user('fix the login bug'))).toBe('human');
    expect(classifyUserLine(user([{ type: 'text', text: 'see screenshot' }, { type: 'image', source: {} }]))).toBe('human');
    expect(classifyUserLine(user([{ type: 'image', source: {} }]))).toBe('human');
  });

  it('rejects lines that only look like user input', () => {
    expect(classifyUserLine(user([{ type: 'tool_result', tool_use_id: 'x', content: 'ok' }]))).toBe('tool_result');
    expect(classifyUserLine(user('hi', { isMeta: true }))).toBe('meta');
    expect(classifyUserLine(user('summary', { isCompactSummary: true }))).toBe('meta');
    expect(classifyUserLine(user('<command-name>/cost</command-name>'))).toBe('command');
    expect(classifyUserLine(user('<local-command-stdout>x</local-command-stdout>'))).toBe('command');
    expect(classifyUserLine(user('Caveat: The messages below were generated by the user while running local commands.'))).toBe('command');
    expect(classifyUserLine(user('<task-notification>done</task-notification>'))).toBe('command');
    expect(classifyUserLine(user('hello', { origin: { kind: 'peer' } }))).toBe('agent');
    expect(classifyUserLine(user('hello', { origin: { kind: 'task-notification' } }))).toBe('agent');
    expect(classifyUserLine(user('hello', { turnOrigin: 'scheduled' }))).toBe('agent');
    expect(classifyUserLine(user('hello', { promptSource: 'system' }))).toBe('agent');
    expect(classifyUserLine(user('subagent task'), true)).toBe('agent');
    expect(classifyUserLine(user(''))).toBe('empty');
    expect(classifyUserLine({ type: 'user', message: 42 })).toBe('empty');
  });

  it('keeps VS Code (sdk) prompts and detects interruptions', () => {
    expect(classifyUserLine(user('refactor this', { promptSource: 'sdk', origin: { kind: 'human' }, turnOrigin: 'human' }))).toBe('human');
    expect(classifyUserLine(user([{ type: 'text', text: '[Request interrupted by user for tool use]' }]))).toBe('interrupt');
  });
});

describe('prompt text features', () => {
  it('detects bare approvals', () => {
    for (const t of ['ok', 'Yes!', 'go ahead', 'continue', 'LGTM', 'ok next task?', "let's do it", '👍', 'thik ache']) expect(isBareApproval(t), t).toBe(true);
    for (const t of ['ok but why is this here', 'yes, and add a test for the empty cart', '', '   ']) expect(isBareApproval(t), t).toBe(false);
  });

  it('detects questions and corrections', () => {
    expect(isQuestion('Why does it retry three times?')).toBe(true);
    expect(isQuestion('what happens if the token expires mid-request')).toBe(true);
    expect(isQuestion('eta keno korcho?')).toBe(true);
    expect(isQuestion('add a retry')).toBe(false);
    expect(isCorrection("no, don't cache that")).toBe(true);
    expect(isCorrection('use the existing helper instead')).toBe(true);
    expect(isCorrection('add a retry')).toBe(false);
  });

  it('extracts file and symbol mentions', () => {
    const m = extractMentions('In `src/orders/checkout.ts`, checkoutTotal() applies applyDiscount twice; see tax_rates too');
    expect(m).toEqual(expect.arrayContaining(['src/orders/checkout.ts', 'checkoutTotal', 'applyDiscount', 'tax_rates']));
  });

  it('extracts declared symbols from changed lines', () => {
    const s = extractSymbols(['export function refreshSession(id: string) {', 'export const TTL_MS = 5;', 'export const handler = async (req) => {', '  async save(item: Item): Promise<void> {', 'class Store {', 'if (x) {']);
    expect(s).toEqual(expect.arrayContaining(['refreshSession', 'TTL_MS', 'handler', 'save', 'Store']));
    expect(s).not.toContain('if');
  });

  it('strips IDE tags and keeps the referenced files', () => {
    const r = cleanPromptText('<ide_opened_file>The user opened the file /repo/src/a.ts in the IDE.</ide_opened_file>fix this<system-reminder>noise</system-reminder>');
    expect(r.text).toBe('fix this');
    expect(r.ideFiles).toEqual([{ path: '/repo/src/a.ts', kind: 'ide_open' }]);
    const s = cleanPromptText('<ide_selection>The user selected the lines 1 to 3 from /repo/b.ts:\ncode</ide_selection>why?');
    expect(s.ideFiles).toEqual([{ path: '/repo/b.ts', kind: 'ide_select' }]);
  });

  it('counts pasted blocks apart from typed words', () => {
    const r = cleanPromptText('why does this fail?\n<pasted_content id="x1">Error: do not call foo() in src/a.ts\nat line 3</pasted_content id="x1">');
    expect(r).toMatchObject({ text: 'why does this fail?', pastedWords: 10 });
  });
});

describe('approvalOf', () => {
  it('maps permission decisions', () => {
    expect(approvalOf({ decision: 'accept', source: 'user_temporary' }, 'default')).toBe('user');
    expect(approvalOf({ decision: 'accept', source: 'config', reasonType: 'classifier' }, 'auto')).toBe('classifier');
    expect(approvalOf({ decision: 'accept', source: 'config', reasonType: 'mode' }, 'acceptEdits')).toBe('mode');
    expect(approvalOf({ decision: 'accept', source: 'config', reasonType: 'other' }, 'default')).toBe('rule');
    expect(approvalOf(undefined, 'acceptEdits')).toBe('mode');
    expect(approvalOf(undefined, 'bypassPermissions')).toBe('bypass');
    expect(approvalOf(undefined, 'auto')).toBe('unrecorded');
  });
});

describe('SessionParser', () => {
  it('ties edits to the turn of the prompt that caused them', () => {
    const r = parse([
      user('add pricing', { uuid: 'p1', permissionMode: 'auto' }),
      toolUse('t1', 'Edit', { file_path: '/repo/a.ts', old_string: 'a', new_string: 'b\nc' }),
      toolResult('t1', { filePath: '/repo/a.ts', structuredPatch: [{ lines: [' x', '-a', '+b', '+c'] }] }, { permissionDecision: { decision: 'accept', source: 'config', reasonType: 'classifier' } }),
      user('ok', { uuid: 'p2' }),
    ]);
    expect(r.prompts.map((p) => [p.uuid, p.kind, p.isBare])).toEqual([['p1', 'human', false], ['p2', 'human', true]]);
    expect(r.edits).toHaveLength(1);
    expect(r.edits[0]).toMatchObject({ turnId: 'p1', filePath: '/repo/a.ts', added: 2, removed: 1, approval: 'classifier', permissionMode: 'auto', created: false });
  });

  it('counts Write creates, MultiEdit input fallback and Bash edit diffs', () => {
    const r = parse([
      user('go', { uuid: 'p1' }),
      toolUse('w', 'Write', { file_path: '/repo/new.ts', content: 'export function hi() {}\n' }),
      toolResult('w', { type: 'create', filePath: '/repo/new.ts', content: 'line1\nexport function hi() {}\n', structuredPatch: [] }),
      toolUse('m', 'MultiEdit', { file_path: '/repo/m.ts', edits: [{ old_string: 'a', new_string: 'b\nc' }, { old_string: 'd\ne', new_string: 'f' }] }),
      toolResult('m', 'ok-as-string'),
      toolUse('b', 'Bash', { command: 'sed -i s/a/b/ x.ts' }),
      toolResult('b', { stdout: '', bashEditDiff: { files: [{ filePath: '/repo/x.ts', hunks: [{ lines: ['-a', '+b'] }] }], changedFiles: ['/repo/x.ts', '/repo/y.ts'] } }),
      toolUse('b2', 'Bash', { command: 'ls' }),
      toolResult('b2', { stdout: 'a b' }),
    ]);
    expect(r.edits.map((e) => [e.tool, e.filePath, e.added, e.removed, e.created])).toEqual([
      ['Write', '/repo/new.ts', 2, 0, true],
      ['MultiEdit', '/repo/m.ts', 3, 3, false],
      ['Bash', '/repo/x.ts', 1, 1, false],
      ['Bash', '/repo/y.ts', 0, 0, false],
    ]);
    expect(r.edits[0]!.symbols).toEqual(['hi']);
  });

  it('skips Bash calls that touch too many files to be authorship', () => {
    const changedFiles = Array.from({ length: BASH_BULK_LIMIT + 1 }, (_, i) => `/repo/f${i}.ts`);
    const r = parse([
      user('switch branch', { uuid: 'p1' }),
      toolUse('b', 'Bash', { command: 'git checkout other' }),
      toolResult('b', { stdout: '', bashEditDiff: { files: [], changedFiles } }),
      toolUse('b2', 'Bash', { command: 'npx prettier --write .' }),
      toolResult('b2', { stdout: '', bashEditDiff: { files: [{ filePath: '/repo/a.ts', hunks: [] }], moreFiles: BASH_BULK_LIMIT } }),
    ]);
    expect(r.edits).toHaveLength(0);
    expect(r.state.bulkBash).toBe(2);
  });

  it('skips failed edits and records user rejections as engagement', () => {
    const r = parse([
      user('fix it', { uuid: 'p1' }),
      toolUse('t1', 'Edit', { file_path: '/repo/a.ts', old_string: 'a', new_string: 'b' }),
      toolResult('t1', 'Error: File has not been read yet.', {}, { is_error: true }),
      toolUse('t2', 'Edit', { file_path: '/repo/a.ts', old_string: 'a', new_string: 'b' }),
      toolResult('t2', 'User rejected', { toolDenialKind: 'user-rejected' }, { is_error: true, content: "The user doesn't want to proceed with this tool use. To tell you how to proceed, the user said:\nno, keep the old name" }),
      toolUse('t3', 'Edit', { file_path: '/repo/a.ts', old_string: 'a', new_string: 'b' }),
      toolResult('t3', 'denied', { toolDenialKind: 'automode-blocked' }, { is_error: true }),
    ]);
    expect(r.edits).toHaveLength(0);
    const rejection = r.prompts.find((p) => p.kind === 'rejection');
    expect(rejection).toMatchObject({ turnId: 'p1', isCorrection: true, excerpt: 'no, keep the old name' });
    expect(r.refs).toEqual([expect.objectContaining({ kind: 'rejected_edit', filePath: '/repo/a.ts', turnId: 'p1' })]);
  });

  it('records plans, answers, interruptions and IDE references', () => {
    const r = parse([
      user('<ide_selection>The user selected the lines 1 to 2 from /repo/s.ts:\nx</ide_selection>plan the session store', { uuid: 'p1' }),
      toolUse('pl', 'ExitPlanMode', { plan: '...' }),
      toolResult('pl', { plan: '...', planWasEdited: true }),
      toolUse('q', 'AskUserQuestion', { questions: [] }),
      toolResult('q', { questions: [], answers: { 'Which store?': 'Redis, with a 30 minute TTL' } }),
      user([{ type: 'text', text: '[Request interrupted by user]' }], { uuid: 'i1' }),
      { type: 'attachment', timestamp: '2026-10-30T10:01:00.000Z', attachment: { type: 'opened_file_in_ide', filename: '/repo/t.ts' } },
      { type: 'attachment', timestamp: '2026-10-30T10:02:00.000Z', attachment: { type: 'edited_text_file', filename: '/repo/s.ts', snippet: '...' } },
    ]);
    expect(r.plans).toEqual([expect.objectContaining({ outcome: 'approved', planEdited: true, turnId: 'p1' })]);
    expect(r.prompts.map((p) => p.kind)).toEqual(['human', 'answer', 'interrupt']);
    expect(r.prompts[1]).toMatchObject({ words: 6, turnId: 'p1' });
    expect(r.refs.map((x) => [x.kind, x.filePath])).toEqual([['ide_select', '/repo/s.ts'], ['ide_open', '/repo/t.ts'], ['external_edit', '/repo/s.ts']]);
  });

  it('ignores file changes reported right after a tool ran, unless the tool was rejected', () => {
    const changed = (ts: string) => ({ type: 'attachment', timestamp: ts, attachment: { type: 'edited_text_file', filename: '/repo/a.ts', snippet: '...' } });
    const r = parse([
      user('tidy up', { uuid: 'p1' }),
      toolUse('b', 'Bash', { command: 'npx prettier -w a.ts' }),
      toolResult('b', { stdout: '' }),
      changed('2026-10-30T10:00:02.000Z'),
      toolUse('e', 'Edit', { file_path: '/repo/a.ts', old_string: 'a', new_string: 'b' }),
      toolResult('e', {}, { toolDenialKind: 'user-rejected' }, { content: "The user doesn't want to proceed with this tool use." }),
      changed('2026-10-30T10:00:03.000Z'),
    ]);
    expect(r.refs.map((x) => [x.kind, x.ts])).toEqual([['rejected_edit', '2026-10-30T10:00:00.000Z'], ['external_edit', '2026-10-30T10:00:03.000Z']]);
  });

  it('survives malformed lines and unknown types', () => {
    const r = parse([
      '{"type":"assistant","message":{"content":[{"type":"tool_use"',
      '[1,2,3]',
      'not json at all',
      { type: 'some-future-line-type', data: { x: 1 } },
      { type: 'user', message: 42 },
      { type: 'user' },
      { type: 'assistant', message: { content: 'just a string' } },
      { type: 'assistant', message: { content: [null, 5, { type: 'tool_use' }] } },
      toolResult('unknown-id', { filePath: '/repo/a.ts' }),
      user('still works', { uuid: 'p1' }),
    ]);
    expect(r.state.bad).toBe(3);
    expect(r.prompts.map((p) => p.uuid)).toEqual(['p1']);
    expect(r.edits).toHaveLength(0);
  });

  it('emits only edits for subagent transcripts', () => {
    const r = parse(
      [
        user('Create the file', { isSidechain: true }),
        toolUse('w', 'Write', { file_path: '/repo/m.ts', content: 'x\n' }),
        toolResult('w', { type: 'create', filePath: '/repo/m.ts', content: 'x\n' }),
        { type: 'attachment', attachment: { type: 'edited_text_file', filename: '/repo/m.ts' } },
      ],
      { sidechain: true },
    );
    expect(r.prompts).toHaveLength(0);
    expect(r.refs).toHaveLength(0);
    expect(r.edits).toEqual([expect.objectContaining({ filePath: '/repo/m.ts', sidechain: true, turnId: null })]);
  });

  it('resumes from saved state with the same result as one full pass', () => {
    const file = join(__dirname, '..', 'fixtures', 'claude', 'projects', '-demo-shop-api', `${SESSION_IDS.fix}.jsonl`);
    const lines = readFileSync(file, 'utf8').trimEnd().split('\n');
    const full = parse(lines);

    for (const cut of [3, 9, lines.length - 2]) {
      const a = new SessionParser();
      lines.slice(0, cut).forEach((l) => a.feedLine(l));
      const first = a.drain();
      const b = new SessionParser({}, JSON.parse(JSON.stringify(a.state)));
      lines.slice(cut).forEach((l) => b.feedLine(l));
      const second = b.drain();
      expect([...first.prompts, ...second.prompts]).toEqual(full.prompts);
      expect([...first.edits, ...second.edits]).toEqual(full.edits);
      expect([...first.refs, ...second.refs]).toEqual(full.refs);
      expect(b.state).toEqual(full.state);
    }
  });
});
